-- RDDT V5 linked evaluation cohort
--
-- Purpose:
--   Select real patients represented in all five authorized V5 tables and
--   export linked rows for end-to-end pipeline evaluation.
--
-- Scope:
--   CENSUS, CLAIMS, ENCOUNTERS, LABS, SURGICAL_HISTORY only.
--   Medication and social history are intentionally excluded.
--
-- How to use:
--   1. Run through the creation of RDDT_V5_EVAL_PATIENTS.
--   2. Review the cohort and join-diagnostic result sets.
--   3. Run each of the five export SELECT statements separately and download
--      each result with the filename shown above it.
--   4. Keep every column and do not replace nulls with empty clinical facts.

USE SCHEMA UHTX_RDDT_CLINICAL_DEV.PUBLIC;

-- Confirm that the warehouse still exposes the expected source columns.
SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    ORDINAL_POSITION
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = CURRENT_SCHEMA()
  AND TABLE_NAME IN ('CENSUS', 'CLAIMS', 'ENCOUNTERS', 'LABS', 'SURGICAL_HISTORY')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- Build a small linked cohort. The red-flag score is used only to select a
-- useful test cohort; it is not clinical evidence and does not replace the
-- configured V5 atom/signal logic.
CREATE OR REPLACE TEMPORARY TABLE RDDT_V5_EVAL_PATIENTS AS
WITH all_five AS (
    SELECT DISTINCT sh.PATIENTID
    FROM SURGICAL_HISTORY sh
    WHERE NULLIF(TRIM(sh.PATIENTID), '') IS NOT NULL
      AND EXISTS (
          SELECT 1 FROM CENSUS c
          WHERE c.PATIENTID = sh.PATIENTID
      )
      AND EXISTS (
          SELECT 1 FROM CLAIMS cl
          WHERE cl.PATIENTID = sh.PATIENTID
      )
      AND EXISTS (
          SELECT 1 FROM ENCOUNTERS e
          WHERE e.PATIENTID = sh.PATIENTID
      )
      AND EXISTS (
          SELECT 1 FROM LABS l
          WHERE l.PATIENTID = sh.PATIENTID
      )
),
claim_features AS (
    SELECT
        p.PATIENTID,
        COUNT(*) AS CLAIM_ROW_COUNT,
        COUNT(DISTINCT cl.ENCOUNTERID) AS CLAIM_ENCOUNTER_COUNT,
        COUNT(DISTINCT UPPER(TRIM(cl.DIAGNOSISCODE))) AS DISTINCT_DIAGNOSIS_COUNT,
        MAX(IFF(
            REGEXP_REPLACE(UPPER(TRIM(cl.DIAGNOSISCODE)), '[^A-Z0-9]', '') LIKE 'E85%',
            1, 0
        )) AS HAS_AMYLOIDOSIS_CODE,
        COUNT_IF(
            REGEXP_LIKE(
                REGEXP_REPLACE(UPPER(TRIM(cl.DIAGNOSISCODE)), '[^A-Z0-9]', ''),
                '^(G56|G60|G61|G62|G63|G90|I42|I43|I50|I951|M48|N04|R80|D472|D891|E85).*'
            )
        ) AS RED_FLAG_CLAIM_COUNT
    FROM all_five p
    JOIN CLAIMS cl
      ON cl.PATIENTID = p.PATIENTID
    WHERE NULLIF(TRIM(cl.DIAGNOSISCODE), '') IS NOT NULL
    GROUP BY p.PATIENTID
),
source_counts AS (
    SELECT
        p.PATIENTID,
        (SELECT COUNT(*) FROM CENSUS c WHERE c.PATIENTID = p.PATIENTID) AS CENSUS_ROWS,
        (SELECT COUNT(*) FROM ENCOUNTERS e WHERE e.PATIENTID = p.PATIENTID) AS ENCOUNTER_ROWS,
        (SELECT COUNT(*) FROM LABS l WHERE l.PATIENTID = p.PATIENTID) AS LAB_ROWS,
        (SELECT COUNT(*) FROM SURGICAL_HISTORY sh WHERE sh.PATIENTID = p.PATIENTID) AS SURGICAL_ROWS
    FROM all_five p
),
ranked AS (
    SELECT
        f.PATIENTID,
        f.HAS_AMYLOIDOSIS_CODE,
        f.RED_FLAG_CLAIM_COUNT,
        f.CLAIM_ROW_COUNT,
        f.CLAIM_ENCOUNTER_COUNT,
        f.DISTINCT_DIAGNOSIS_COUNT,
        s.CENSUS_ROWS,
        s.ENCOUNTER_ROWS,
        s.LAB_ROWS,
        s.SURGICAL_ROWS,
        CASE
            WHEN f.HAS_AMYLOIDOSIS_CODE = 1 THEN 'CONFIRMED_CODE_PATH'
            WHEN f.RED_FLAG_CLAIM_COUNT > 0 THEN 'SUSPICION_CODE_PATH'
            ELSE 'FULL_PROFILE_CONTROL'
        END AS SELECTION_REASON,
        ROW_NUMBER() OVER (
            ORDER BY
                f.HAS_AMYLOIDOSIS_CODE DESC,
                f.RED_FLAG_CLAIM_COUNT DESC,
                f.DISTINCT_DIAGNOSIS_COUNT DESC,
                f.CLAIM_ROW_COUNT DESC,
                f.PATIENTID
        ) AS COHORT_RANK
    FROM claim_features f
    JOIN source_counts s
      ON s.PATIENTID = f.PATIENTID
)
SELECT *
FROM ranked
WHERE COHORT_RANK <= 20;

-- Cohort manifest and source row volumes.
SELECT *
FROM RDDT_V5_EVAL_PATIENTS
ORDER BY COHORT_RANK;

-- Validate whether CLAIMS.ENCOUNTERID can safely inherit VISITDATE from a
-- unique patient-plus-visit match. Ambiguous dates must not be used.
WITH encounter_keys AS (
    SELECT
        PATIENTID,
        VISITID,
        COUNT(*) AS ENCOUNTER_ROWS_FOR_KEY,
        COUNT(DISTINCT TRY_TO_TIMESTAMP_NTZ(VISITDATE)) AS DISTINCT_VISIT_DATES,
        MIN(TRY_TO_TIMESTAMP_NTZ(VISITDATE)) AS UNIQUE_VISIT_DATE
    FROM ENCOUNTERS
    WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
    GROUP BY PATIENTID, VISITID
)
SELECT
    COUNT(*) AS CLAIM_ROWS,
    COUNT_IF(NULLIF(TRIM(cl.ENCOUNTERID), '') IS NULL) AS CLAIM_ROWS_WITHOUT_ENCOUNTER_ID,
    COUNT_IF(ek.VISITID IS NULL) AS CLAIM_ROWS_WITHOUT_ENCOUNTER_MATCH,
    COUNT_IF(ek.VISITID IS NOT NULL AND ek.DISTINCT_VISIT_DATES = 1) AS CLAIM_ROWS_WITH_UNIQUE_DATE,
    COUNT_IF(ek.DISTINCT_VISIT_DATES > 1) AS CLAIM_ROWS_WITH_AMBIGUOUS_DATES
FROM CLAIMS cl
LEFT JOIN encounter_keys ek
  ON ek.PATIENTID = cl.PATIENTID
 AND ek.VISITID = cl.ENCOUNTERID
WHERE cl.PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS);

-- Validate the LABS.ENCOUNTERKEY to ENCOUNTERS.VISITID relationship separately.
WITH encounter_keys AS (
    SELECT DISTINCT PATIENTID, VISITID
    FROM ENCOUNTERS
    WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
)
SELECT
    COUNT(*) AS LAB_ROWS,
    COUNT_IF(NULLIF(TRIM(l.ENCOUNTERKEY), '') IS NULL) AS LAB_ROWS_WITHOUT_ENCOUNTER_KEY,
    COUNT_IF(ek.VISITID IS NULL) AS LAB_ROWS_WITHOUT_ENCOUNTER_MATCH,
    COUNT_IF(ek.VISITID IS NOT NULL) AS LAB_ROWS_WITH_ENCOUNTER_MATCH
FROM LABS l
LEFT JOIN encounter_keys ek
  ON ek.PATIENTID = l.PATIENTID
 AND ek.VISITID = l.ENCOUNTERKEY
WHERE l.PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS);

-- Review exact source volumes before downloading the five extracts.
SELECT 'CENSUS' AS SOURCE_TABLE, COUNT(*) AS ROW_COUNT
FROM CENSUS WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
UNION ALL
SELECT 'CLAIMS', COUNT(*)
FROM CLAIMS WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
UNION ALL
SELECT 'ENCOUNTERS', COUNT(*)
FROM ENCOUNTERS WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
UNION ALL
SELECT 'LABS', COUNT(*)
FROM LABS WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
UNION ALL
SELECT 'SURGICAL_HISTORY', COUNT(*)
FROM SURGICAL_HISTORY WHERE PATIENTID IN (SELECT PATIENTID FROM RDDT_V5_EVAL_PATIENTS)
ORDER BY SOURCE_TABLE;

-- Export as: CENSUS_linked_eval.csv
SELECT c.*
FROM CENSUS c
JOIN RDDT_V5_EVAL_PATIENTS p ON p.PATIENTID = c.PATIENTID
ORDER BY p.COHORT_RANK, c.PATIENTID;

-- Export as: CLAIMS_linked_eval.csv
SELECT cl.*
FROM CLAIMS cl
JOIN RDDT_V5_EVAL_PATIENTS p ON p.PATIENTID = cl.PATIENTID
ORDER BY p.COHORT_RANK, cl.PATIENTID, cl.CLAIMNO, cl.CLAIMLINENO;

-- Export as: ENCOUNTERS_linked_eval.csv
SELECT e.*
FROM ENCOUNTERS e
JOIN RDDT_V5_EVAL_PATIENTS p ON p.PATIENTID = e.PATIENTID
ORDER BY p.COHORT_RANK, e.PATIENTID, TRY_TO_TIMESTAMP_NTZ(e.VISITDATE), e.VISITID;

-- Export as: LABS_linked_eval.csv
SELECT l.*
FROM LABS l
JOIN RDDT_V5_EVAL_PATIENTS p ON p.PATIENTID = l.PATIENTID
ORDER BY p.COHORT_RANK, l.PATIENTID, TRY_TO_TIMESTAMP_NTZ(l.OBSERVATIONDATETIME), l.LABTESTKEY;

-- Export as: SURGICAL_HISTORY_linked_eval.csv
SELECT sh.*
FROM SURGICAL_HISTORY sh
JOIN RDDT_V5_EVAL_PATIENTS p ON p.PATIENTID = sh.PATIENTID
ORDER BY p.COHORT_RANK, sh.PATIENTID, TRY_TO_TIMESTAMP_NTZ(sh."DATE"), sh.SURGICALHISTORYID;
