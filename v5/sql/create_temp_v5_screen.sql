CLUSTER BY ("PATIENTID")
AS
SELECT SRC.*
FROM "UHTX_RDDT_CLINICAL_DEV"."PUBLIC"."CENSUS" SRC
JOIN (
  SELECT DISTINCT CAST("PATIENTID" AS VARCHAR) AS PATIENT_ID
  FROM "UHTX_RDDT_CLINICAL_DEV"."PUBLIC"."TEMP_V5_SCREEN_CLAIM"
  WHERE "PATIENTID" IS NOT NULL
) IDS
  ON CAST(SRC."PATIENTID" AS VARCHAR) = IDS.PATIENT_ID;

SELECT 'TEMP_V5_SCREEN_CLAIM' AS TABLE_NAME, COUNT(*) AS ROW_COUNT, COUNT(DISTINCT "PATIENTID") AS PATIENTS
FROM "UHTX_RDDT_CLINICAL_DEV"."PUBLIC"."TEMP_V5_SCREEN_CLAIM"
UNION ALL
SELECT 'TEMP_V5_CENSUS', COUNT(*), COUNT(DISTINCT "PATIENTID")
FROM "UHTX_RDDT_CLINICAL_DEV"."PUBLIC"."TEMP_V5_CENSUS";
